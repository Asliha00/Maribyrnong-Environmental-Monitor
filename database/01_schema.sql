CREATE SCHEMA IF NOT EXISTS app;
SET search_path TO app;

-- ---------- Access control ----------
CREATE TABLE IF NOT EXISTS roles (
    role_id      INTEGER PRIMARY KEY,
    role_name    TEXT NOT NULL UNIQUE,
    permissions  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    user_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             TEXT NOT NULL UNIQUE,
    email                TEXT NOT NULL UNIQUE,
    password_hash        TEXT NOT NULL,
    role_id              INTEGER NOT NULL REFERENCES roles(role_id),
    is_active            INTEGER NOT NULL DEFAULT 1,
    must_change_password INTEGER NOT NULL DEFAULT 1,
    failed_attempts      INTEGER NOT NULL DEFAULT 0,
    locked_until         TIMESTAMPTZ,
    mfa_enabled          INTEGER NOT NULL DEFAULT 0,
    mfa_secret_encrypted TEXT,
    mfa_last_used_step   BIGINT,          -- SEC-07: last accepted TOTP time step (no code reuse)
    tokens_valid_after   TIMESTAMPTZ,     -- SEC-08: tokens issued before this are rejected
    last_login_at        TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- Phase 1 columns for databases created before they existed (safe to re-run)
ALTER TABLE users ADD COLUMN IF NOT EXISTS mfa_last_used_step BIGINT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS tokens_valid_after TIMESTAMPTZ;

INSERT INTO roles (role_id, role_name, permissions) VALUES
