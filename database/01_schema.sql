 (2, 'Environmental Analyst', 'view_data,filter_data,export_data,view_quality'),
 (3, 'System Administrator',  'view_data,filter_data,export_data,view_quality,manage_sensors,manage_users,manage_thresholds')
ON CONFLICT (role_id) DO NOTHING;

-- ---------- Sensors ----------
CREATE TABLE IF NOT EXISTS sensors (
    sensor_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_code        TEXT NOT NULL UNIQUE,
    sensor_name        TEXT NOT NULL UNIQUE,
    device_family      TEXT NOT NULL,
    hardware_id        TEXT,
    latitude           DOUBLE PRECISION,
    longitude          DOUBLE PRECISION,
    location_verified  INTEGER NOT NULL DEFAULT 0,
    land_use           TEXT NOT NULL,
    installation_date  DATE,
    status             TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active','Inactive')),
    auth_key_hash      TEXT,
    notes              TEXT,
    first_reading_utc  TIMESTAMPTZ,
    last_reading_utc   TIMESTAMPTZ,
    sensitive_receptor INTEGER NOT NULL DEFAULT 0   -- e.g. a childcare centre (Insights equity lens)
);
-- Phase 6 column for databases created before it existed (safe to re-run)
ALTER TABLE sensors ADD COLUMN IF NOT EXISTS sensitive_receptor INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS sensor_variables (
    sensor_id   INTEGER NOT NULL REFERENCES sensors(sensor_id),
    variable    TEXT NOT NULL,
    unit        TEXT NOT NULL,
    raw_column  TEXT NOT NULL,
    PRIMARY KEY (sensor_id, variable)
);

-- ---------- Ingestion runs (created before readings for the FK) ----------
CREATE TABLE IF NOT EXISTS ingestion_runs (
    run_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_file     TEXT NOT NULL,
    file_sha256     TEXT NOT NULL,
    sensor_id       INTEGER REFERENCES sensors(sensor_id),
    rows_read       INTEGER,
    rows_inserted   INTEGER,
    rows_duplicate  INTEGER,
    values_rejected INTEGER,
    values_flagged  INTEGER,
    storage_path    TEXT,            -- pathname of the original file in the private Vercel Blob store
    started_at      TIMESTAMPTZ NOT NULL,
    finished_at     TIMESTAMPTZ
);

-- ---------- Readings ----------
CREATE TABLE IF NOT EXISTS readings (
    reading_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id        INTEGER NOT NULL REFERENCES sensors(sensor_id),
    ts_utc           TIMESTAMPTZ NOT NULL,
    ts_local         TEXT NOT NULL,
    temperature_c    DOUBLE PRECISION,
    humidity_pct     DOUBLE PRECISION,
    pm1              DOUBLE PRECISION,
    pm25             DOUBLE PRECISION,
    pm10             DOUBLE PRECISION,
    no2_ppb          DOUBLE PRECISION,
    co_ppb           DOUBLE PRECISION,
    co2_ppm          DOUBLE PRECISION,
    pressure_hpa     DOUBLE PRECISION,
    aqi              DOUBLE PRECISION,
    battery_v        DOUBLE PRECISION,
    qc_flags         TEXT,
    ingestion_run_id INTEGER REFERENCES ingestion_runs(run_id),
    UNIQUE (sensor_id, ts_utc)
);
CREATE INDEX IF NOT EXISTS idx_readings_ts ON readings(ts_utc);

-- ---------- Error log ----------
CREATE TABLE IF NOT EXISTS error_log (
    error_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_id        INTEGER REFERENCES sensors(sensor_id),
    ts_utc           TIMESTAMPTZ,
    error_type       TEXT NOT NULL,
    variable         TEXT,
    raw_value        TEXT,
    description      TEXT,
    ingestion_run_id INTEGER REFERENCES ingestion_runs(run_id),
    logged_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_error_sensor ON error_log(sensor_id, error_type);

-- ---------- Aggregates ----------
CREATE TABLE IF NOT EXISTS aggregates (
    sensor_id          INTEGER NOT NULL REFERENCES sensors(sensor_id),
    period             TEXT NOT NULL CHECK (period IN ('hour','day','month')),
    bucket_start_local TEXT NOT NULL,
    season             TEXT NOT NULL,
    variable           TEXT NOT NULL,
    mean               DOUBLE PRECISION,
    min                DOUBLE PRECISION,
    max                DOUBLE PRECISION,
    n                  INTEGER NOT NULL,
    completeness_pct   DOUBLE PRECISION,
    is_valid           INTEGER NOT NULL,
    qc_mode            TEXT NOT NULL DEFAULT 'all' CHECK (qc_mode IN ('all','clean')),
                                          -- all: every kept value; clean: QC-flagged values left out (DECISIONS D-028)
    PRIMARY KEY (sensor_id, period, bucket_start_local, variable, qc_mode)
);
-- Phase 2 migration for databases created before qc_mode existed (safe to re-run)
ALTER TABLE aggregates ADD COLUMN IF NOT EXISTS qc_mode TEXT NOT NULL DEFAULT 'all';
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'aggregates_qc_mode_check') THEN
    ALTER TABLE aggregates ADD CONSTRAINT aggregates_qc_mode_check CHECK (qc_mode IN ('all','clean'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
                 WHERE i.indrelid = 'aggregates'::regclass AND i.indisprimary AND a.attname = 'qc_mode') THEN
    ALTER TABLE aggregates DROP CONSTRAINT aggregates_pkey;
    ALTER TABLE aggregates ADD PRIMARY KEY (sensor_id, period, bucket_start_local, variable, qc_mode);
  END IF;
END $$;
DROP INDEX IF EXISTS idx_agg_lookup;
CREATE INDEX IF NOT EXISTS idx_agg_lookup_qc ON aggregates(period, variable, qc_mode, bucket_start_local);

-- ---------- Thresholds ----------
CREATE TABLE IF NOT EXISTS thresholds (
    threshold_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variable     TEXT NOT NULL,
    period       TEXT NOT NULL,
    operator     TEXT NOT NULL CHECK (operator IN ('>','>=')),
    value        DOUBLE PRECISION NOT NULL,
    label        TEXT NOT NULL,
    source       TEXT,
    updated_by   INTEGER REFERENCES users(user_id),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (variable, period, value)
);

CREATE TABLE IF NOT EXISTS threshold_history (
    history_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    threshold_id INTEGER NOT NULL REFERENCES thresholds(threshold_id),
    old_value    DOUBLE PRECISION,
    new_value    DOUBLE PRECISION NOT NULL,
    reason       TEXT NOT NULL,
    changed_by   INTEGER REFERENCES users(user_id),
    changed_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS exceedances (
    sensor_id          INTEGER NOT NULL REFERENCES sensors(sensor_id),
    threshold_id       INTEGER NOT NULL REFERENCES thresholds(threshold_id),
    date_local         TEXT NOT NULL,
    observed_value     DOUBLE PRECISION NOT NULL,
    completeness_pct   DOUBLE PRECISION,
    PRIMARY KEY (sensor_id, threshold_id, date_local)
);

-- ---------- Reports, audit, tokens ----------
CREATE TABLE IF NOT EXISTS reports (
    report_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER REFERENCES users(user_id),
    report_type  TEXT NOT NULL,
    format       TEXT NOT NULL CHECK (format IN ('csv','pdf')),
    filter_json  TEXT NOT NULL,
    row_count    INTEGER,
    created_date TIMESTAMPTZ NOT NULL DEFAULT now(),
    file_path    TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
    audit_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER REFERENCES users(user_id),
    action      TEXT NOT NULL,
    detail_json TEXT,
    ip_address  TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS revoked_tokens (
    jti        TEXT PRIMARY KEY,
    user_id    INTEGER REFERENCES users(user_id),
    expires_at TIMESTAMPTZ NOT NULL
);

-- Shared rate-limit counters (SEC-23). Vercel runs many short-lived function
-- instances, so in-memory limiters cannot see each other's requests; a fixed
-- window counter in the database is shared by every instance.
CREATE TABLE IF NOT EXISTS rate_limits (
    bucket       TEXT NOT NULL,          -- e.g. 'login:ip:203.0.113.5', 'export:user:7'
    window_start TIMESTAMPTZ NOT NULL,
    hits         INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (bucket, window_start)
);

-- Single-use 2FA recovery codes for administrators (SEC-07, D-037). A code is
-- SELECTOR-SECRET: the 4-character selector finds the row, and only an argon2id hash
-- of the 12-character secret is stored. Codes are never deleted: used and replaced
-- codes keep their timestamps for the audit trail.
CREATE TABLE IF NOT EXISTS mfa_recovery_codes (
    code_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    selector   TEXT NOT NULL,
    code_hash  TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    used_at    TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_mfa_recovery_codes_user ON mfa_recovery_codes (user_id, selector);
